#!/usr/bin/env node
/*
 * Builds the fulfilment catalog and the private download files for stripe-hub.
 *
 *   node scripts/build-fulfilment.mjs --catalog-only   regenerate src/fulfilment/catalog.json
 *   node scripts/build-fulfilment.mjs                  catalog + private/ files (run on the build host)
 *
 * Sources (sibling repos under projects/mdo3d/):
 *   layoffleads/site.config.json          Pro Payment Links; full-history CSV via scripts/export-csv.mjs
 *   promptsforbusiness/site.config.json   pack + bundle Payment Links; Markdown via scripts/export-pack.mjs all
 * private/ is gitignored and is shipped only inside the Vercel function (vercel.json includeFiles).
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HUB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LL = path.resolve(HUB, '..', 'layoffleads');
const PFB = path.resolve(HUB, '..', 'promptsforbusiness');
const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const catalogOnly = process.argv.includes('--catalog-only');

const ll = readJson(path.join(LL, 'site.config.json'));
const pfb = readJson(path.join(PFB, 'site.config.json'));
const packs = fs.readdirSync(path.join(PFB, 'content/packs')).filter((f) => f.endsWith('.json'))
  .map((f) => readJson(path.join(PFB, 'content/packs', f))).sort((a, b) => a.order - b.order);

const LL_FILE = { path: 'layoffleads/layoffleads-full-history.csv', label: 'LayoffLeads full-history CSV (every notice since January 2025)' };
const catalog = {
  _readme: 'GENERATED by scripts/build-fulfilment.mjs from the layoffleads and promptsforbusiness site.config.json files. Do not edit by hand.',
  sites: {
    layoffleads: {
      name: ll.siteName, url: ll.baseUrl, contactEmail: ll.contactEmail, fromEnv: 'FULFIL_FROM_LAYOFFLEADS',
      afterDownload: 'Weekly alerts: reply with the states, industries and companies you want to follow, and your weekly alert emails start from the next weekly run.',
    },
    pfb: {
      name: pfb.name, url: pfb.url, contactEmail: pfb.contactEmail, fromEnv: 'FULFIL_FROM_PFB',
      afterDownload: 'The file is Markdown: it opens in any text editor, Notion, Google Docs or Word.',
    },
  },
  products: {},
};

const pro = ll.plans.pro;
for (const [period, plan] of [['monthly', pro.monthly], ['annual', pro.annual]]) {
  if (!plan || !plan.paymentLink) continue;
  catalog.products[`layoffleads-pro-${period}`] = {
    site: 'layoffleads', title: `${ll.siteName} Pro (${plan.label})`, paymentLink: plan.paymentLink,
    files: [LL_FILE], followUp: 'Add the buyer to the weekly alert run once they reply with their states/industries/companies.',
  };
}
for (const pk of packs) {
  const link = pfb.checkout.packs[pk.slug];
  if (!link) continue;
  catalog.products[`pfb-${pk.slug}`] = {
    site: 'pfb', title: `${pk.title} (prompt pack)`, paymentLink: link,
    files: [{ path: `pfb/${pk.slug}.md`, label: `${pk.title} (Markdown)` }],
  };
}
if (pfb.checkout.bundle) {
  catalog.products['pfb-all-access'] = {
    site: 'pfb', title: `${pfb.pricing.bundleName} (all ${packs.length} packs)`, paymentLink: pfb.checkout.bundle,
    files: [{ path: 'pfb/all-access.md', label: `All ${packs.length} packs in one Markdown file` }],
    followUp: 'Bundle promises future packs: email new packs to bundle buyers when added.',
  };
}
fs.writeFileSync(path.join(HUB, 'src/fulfilment/catalog.json'), JSON.stringify(catalog, null, 2) + '\n');
console.log(`catalog: ${Object.keys(catalog.products).length} products`);
if (catalogOnly) process.exit(0);

// Private files.
const priv = path.join(HUB, 'private');
fs.mkdirSync(path.join(priv, 'layoffleads'), { recursive: true });
fs.mkdirSync(path.join(priv, 'pfb'), { recursive: true });
const out = execFileSync(process.execPath, [path.join(LL, 'scripts/export-csv.mjs')], { cwd: LL, encoding: 'utf8' });
const m = /to (exports\/\S+\.csv)/.exec(out);
if (!m) throw new Error(`export-csv.mjs output not understood: ${out}`);
fs.copyFileSync(path.join(LL, m[1]), path.join(priv, LL_FILE.path));
execFileSync(process.execPath, [path.join(PFB, 'scripts/export-pack.mjs'), 'all'], { cwd: PFB, encoding: 'utf8' });
for (const f of fs.readdirSync(path.join(PFB, 'private-exports')).filter((x) => x.endsWith('.md'))) {
  fs.copyFileSync(path.join(PFB, 'private-exports', f), path.join(priv, 'pfb', f));
}
// Every catalog file must exist.
const missing = Object.values(catalog.products).flatMap((p) => p.files.map((f) => f.path)).filter((f) => !fs.existsSync(path.join(priv, f)));
if (missing.length) { console.error(`missing private files: ${missing.join(', ')}`); process.exit(1); }
console.log(`private files ready (${fs.readdirSync(path.join(priv, 'pfb')).length} pfb, 1 layoffleads)`);
