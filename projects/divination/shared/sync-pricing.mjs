#!/usr/bin/env node
// Copies each product's slice of shared/pricing.json into the places that
// deploy on their own (each API is its own Vercel project rooted at api/, each
// frontend is its own project), so the price a page shows is the price the API
// charges (JARVIS #63). Zero dependencies: plain node file copy.
//
//   node sync-pricing.mjs                 write every copy
//   node sync-pricing.mjs --check         exit 1 if any copy is missing or drifted
//   node sync-pricing.mjs --repo astrology/astrology=/abs/path ...
//        point a nested repo (submodule gitlink) at another checkout/worktree
//   --strict                              also fail when a nested repo root is absent
//
// A nested repo whose root is absent (empty gitlink dir) is reported as SKIP.
//
// Also synced from shared/templates/: api-pricing.js -> <api>/src/pricing.js
// (the server-side lookup), api-pricing.test.js + test-cases.json ->
// <api>/test/pricing.test.js and, for static frontends, price-display.js ->
// public/js/price-display.js (fills [data-price] elements at runtime). In each
// static frontend's public/index.html the text of every data-price="<type>"
// element is rewritten to the configured price, so shown == charged even
// before JS runs; an unknown type there is an error.

import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const divination = resolve(here, '..');

// product -> { api: dir under divination, fe: [repoRoot (relative to divination), file inside repo] }
const TARGETS = {
  astrology:  { api: 'astrology/api',  fe: ['astrology/astrology', 'public/js/config/pricing.json'], static: true },
  dreams:     { api: 'dreams/api',     fe: ['dreams/dream-interpreter', 'public/js/config/pricing.json'], static: true },
  fengshui:   { api: 'fengshui/api',   fe: ['fengshui/feng-shui-analyzer', 'app/lib/pricing.json'] },
  iching:     { api: 'iching/api',     fe: ['iching/iching', 'public/js/config/pricing.json'], static: true },
  numerology: { api: 'numerology/api', fe: ['numerology/numerology-app', 'public/js/config/pricing.json'], static: true },
  oracle:     { api: 'oracle/api',     fe: ['oracle/oracle-cards', 'public/js/config/pricing.json'], static: true },
  pastlives:  { api: 'pastlives/api',  fe: ['pastlives/past-life-insights', 'app/lib/pricing.json'] },
  runes:      { api: 'runes/api',      fe: ['runes/runes', 'public/js/config/pricing.json'], static: true },
  tarot:      { api: 'tarot/api',      fe: ['tarot/tarot-cards', 'public/js/config/pricing.json'], static: true }
};

const args = process.argv.slice(2);
const check = args.includes('--check');
const strict = args.includes('--strict');
const repoOverrides = {};
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--repo') {
    const [k, v] = String(args[++i] || '').split('=');
    if (!k || !v) { console.error('--repo expects rel/path=/abs/path'); process.exit(2); }
    repoOverrides[k] = resolve(v);
  }
}

const source = JSON.parse(readFileSync(join(here, 'pricing.json'), 'utf8'));
const apiPricingJs = readFileSync(join(here, 'templates', 'api-pricing.js'), 'utf8');
const priceDisplayJs = readFileSync(join(here, 'templates', 'price-display.js'), 'utf8');
const apiTestTpl = readFileSync(join(here, 'templates', 'api-pricing.test.js'), 'utf8');
const testCases = JSON.parse(readFileSync(join(here, 'test-cases.json'), 'utf8'));

function formatCents(c) {
  return '$' + (c % 100 === 0 ? String(c / 100) : (c / 100).toFixed(2));
}

// Rewrites the text of <tag ... data-price="type" ...>TEXT</tag> to the price.
function withHtmlPrices(html, product, types, file) {
  return html.replace(/(<([a-zA-Z][a-zA-Z0-9]*)\b[^>]*\bdata-price="([^"]*)"[^>]*>)([^<]*)(<\/\2>)/g,
    (m, open, tag, type, text, close) => {
      if (!Object.prototype.hasOwnProperty.call(types, type)) {
        errors.push(`${file}: data-price="${type}" is not a ${product} readingType`);
        return m;
      }
      return open + formatCents(types[type].amount_cents) + close;
    });
}
const errors = [];
const currency = source.currency || 'usd';

function validate(product, types) {
  for (const [type, entry] of Object.entries(types)) {
    if (!Number.isInteger(entry.amount_cents) || entry.amount_cents <= 0) {
      errors.push(`${product}.${type}: amount_cents must be a positive integer`);
    }
    if (typeof entry.label !== 'string' || !entry.label) errors.push(`${product}.${type}: label required`);
  }
}

function sliceFor(product) {
  return JSON.stringify({
    _generated: 'GENERATED by projects/divination/shared/sync-pricing.mjs from shared/pricing.json. Do not edit by hand.',
    product,
    currency,
    types: source.products[product]
  }, null, 2) + '\n';
}

let drift = 0, written = 0, ok = 0, skipped = 0;
function handle(file, want) {
  const have = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (have === want) { ok++; return; }
  if (check) {
    drift++;
    console.error(`${have === null ? 'MISSING' : 'DRIFT  '} ${file}`);
    return;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, want);
  written++;
  console.log(`wrote   ${file}`);
}

for (const product of Object.keys(source.products)) {
  if (!TARGETS[product]) errors.push(`${product}: no sync target defined`);
}
for (const [product, t] of Object.entries(TARGETS)) {
  const types = source.products[product];
  if (!types) { errors.push(`${product}: missing from shared/pricing.json`); continue; }
  validate(product, types);
  const want = sliceFor(product);
  handle(join(divination, t.api, 'src', 'pricing.json'), want);
  handle(join(divination, t.api, 'src', 'pricing.js'), apiPricingJs);
  if (!testCases[product]) errors.push(`${product}: missing from shared/test-cases.json`);
  else handle(join(divination, t.api, 'test', 'pricing.test.js'),
    apiTestTpl.replace('__CASES__', JSON.stringify({ product, ...testCases[product] }, null, 2)));

  const [repoRel, fileRel] = t.fe;
  const root = repoOverrides[repoRel] || join(divination, repoRel);
  const present = existsSync(root) && readdirSync(root).length > 0;
  if (!present) {
    skipped++;
    console.warn(`SKIP    ${root} (repo root absent; pass --repo ${repoRel}=<checkout>)`);
    continue;
  }
  handle(join(root, fileRel), want);
  if (t.static) {
    handle(join(root, 'public', 'js', 'price-display.js'), priceDisplayJs);
    const index = join(root, 'public', 'index.html');
    if (existsSync(index)) {
      const html = readFileSync(index, 'utf8');
      handle(index, withHtmlPrices(html, product, types, index));
    }
  }
}

if (errors.length) { for (const e of errors) console.error(`ERROR   ${e}`); process.exit(1); }
console.log(`${check ? 'check' : 'sync'}: ${ok} in sync, ${written} written, ${drift} drifted, ${skipped} skipped`);
if (drift || (strict && skipped)) process.exit(1);
